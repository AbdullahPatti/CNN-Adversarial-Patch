"""Paper tables, figures and in-text numbers, all generated from results/*.json (no number is typed by hand).

Writes paper/generated/macros.tex (\\R{key} -> number), paper/generated/tab_*.tex and paper/figures/*.pdf.
Keys:  <metric>:<model> = mean over seeds (%), <metric>:<model>:sd = std, d:<metric>:<comparison> = paired
difference (pp) with :lo / :hi (95% t-CI over seeds), b:<metric>:<comparison> = image bootstrap, same suffixes.
An unknown key prints a bold ?? in the PDF, so a typo cannot pass silently.

Usage:  python -m src.paper_assets
"""
import json
import re
from pathlib import Path

import matplotlib
import matplotlib.lines
import numpy as np

matplotlib.use("Agg")
import matplotlib.pyplot as plt  # noqa: E402

from src.stats import BASE, MODELS, SEEDS, _load, bootstrap, collect, comparisons, mean_std, paired  # noqa: E402

OUT, FIG = Path("paper/generated"), Path("paper/figures")
FAMILIES = {  # name -> (models at 2x/4x/8x, colour, marker, linestyle); reference palette slots 1-4
    "Quantization": (["quant_2x_fp16", "quant_4x_int8", "quant_8x_int4"], "#2a78d6", "o", "-"),
    "Pruning": (["prune_2x", "prune_4x", "prune_8x"], "#eb6834", "s", "--"),
    "Dense-small": (["dense_small_2x", "dense_small_4x", "dense_small_8x"], "#1baf7a", "^", "-."),
    "Distillation": (["kd_2x", "kd_4x", "kd_8x"], "#eda100", "D", ":"),
}
LABEL = {"baseline_resnet18": "Baseline", "quant_2x_fp16": "FP16", "quant_4x_int8": "INT8", "quant_8x_int4": "INT4",
         "prune_2x": "Prune 2$\\times$", "prune_4x": "Prune 4$\\times$", "prune_8x": "Prune 8$\\times$",
         "dense_small_2x": "Dense-small 2$\\times$", "dense_small_4x": "Dense-small 4$\\times$",
         "dense_small_8x": "Dense-small 8$\\times$", "kd_2x": "KD 2$\\times$", "kd_4x": "KD 4$\\times$",
         "kd_8x": "KD 8$\\times$"}
INK, MUTED = "#0b0b0b", "#52514e"


def slug(s):
    return re.sub(r"[^a-z0-9]+", "", s.lower().replace("->", "to"))


class Macros:
    def __init__(self):
        self.d = {}

    def put(self, key, value):
        assert key not in self.d or self.d[key] == value, key
        self.d[key] = value

    def write(self, path):
        lines = ["% generated by src/paper_assets.py -- do not edit",
                 "\\newcommand{\\R}[1]{\\ifcsname r@#1\\endcsname\\csname r@#1\\endcsname\\else\\textbf{??#1}\\fi}"]
        lines += [f"\\expandafter\\def\\csname r@{k}\\endcsname{{{v}}}" for k, v in sorted(self.d.items())]
        path.write_text("\n".join(lines) + "\n")


def f1(v):
    return f"{v * 100:.1f}"


def sgn(v):
    return f"{v * 100:+.1f}".replace("-", "$-$")


def ms(values, metric, model):
    m, s, _ = mean_std(values[metric].get(model, []))
    return (None, None) if m is None else (m, s)


def cell(values, metric, model):
    m, s = ms(values, metric, model)
    return "--" if m is None else f"{f1(m)}{{\\scriptsize$\\pm${f1(s)}}}"


def diff_cell(p):
    if p is None:
        return "--"
    sig = p["lo"] > 0 or p["hi"] < 0
    txt = f"{sgn(p['diff'])} {{\\scriptsize[{sgn(p['lo'])}, {sgn(p['hi'])}]}}"
    return f"\\textbf{{{txt}}}" if sig else txt


def table(path, header, rows, colspec, groups=None):
    """Booktabs tabular; groups = set of row indices after which a \\midrule goes."""
    out = [f"\\begin{{tabular}}{{{colspec}}}", "\\toprule", " & ".join(header) + " \\\\", "\\midrule"]
    for i, r in enumerate(rows):
        out.append(" & ".join(r) + " \\\\")
        if groups and i in groups:
            out.append("\\midrule")
    out += ["\\bottomrule", "\\end{tabular}"]
    path.write_text("\n".join(out) + "\n")


ROW_GROUPS = {0, 3, 6, 9}  # baseline | quant | prune | dense-small | KD


def main():
    OUT.mkdir(parents=True, exist_ok=True)
    FIG.mkdir(parents=True, exist_ok=True)
    values, images = collect()
    mac = Macros()

    # ---- extra per-seed values not in stats.collect: storage ratio, nonzero params, LaVAN noise control
    extra = {"ratio": {}, "nonzero": {}}
    for model in MODELS:
        ms42 = _load(model)
        extra["ratio"][model] = ms42.get("ratio_vs_baseline", 1.0)
        extra["nonzero"][model] = ms42["nonzero_params"]
    noise = {}
    for model in MODELS[1:]:
        vals = []
        for sfx in SEEDS.values():
            t = _load(f"transfer{sfx}")
            vals.append(t["lavan"][BASE + sfx][model + sfx]["side_5_untargeted"]["noise_rate"])
        noise[model] = vals
    values["T L5 noise"] = noise

    # ---- macros: every mean / std, every paired difference, every bootstrap
    for metric, per_model in values.items():
        for model in per_model:
            m, s = ms(values, metric, model)
            if m is not None:
                mac.put(f"{slug(metric)}:{model}", f1(m))
                mac.put(f"{slug(metric)}:{model}:sd", f1(s))
    for label, a, b in comparisons():
        for metric in values:
            va, vb = values[metric].get(a), values[metric].get(b)
            p = paired(va, vb) if va and vb else None
            if p:
                k = f"d:{slug(metric)}:{a}-{b}"
                mac.put(k, sgn(p["diff"]))
                mac.put(k + ":lo", sgn(p["lo"]))
                mac.put(k + ":hi", sgn(p["hi"]))
                mac.put(k + ":abs", f"{abs(p['diff']) * 100:.1f}")
        for metric in images:
            ia, ib = images[metric].get(a), images[metric].get(b)
            if ia is not None and ib is not None:
                p = bootstrap(ia, ib)
                k = f"b:{slug(metric)}:{a}-{b}"
                mac.put(k, sgn(p["diff"]))
                mac.put(k + ":lo", sgn(p["lo"]))
                mac.put(k + ":hi", sgn(p["hi"]))
    for model in MODELS:  # defended - vanilla
        for s in (5, 8):
            p = paired(values[f"cert{s} def"][model], values[f"cert{s} vanilla"][model])
            mac.put(f"d:cert{s}gain:{model}", f"{p['diff'] * 100:.1f}")
        mac.put(f"ratio:{model}", f"{extra['ratio'][model]:.2f}")
        mac.put(f"nonzero:{model}", f"{extra['nonzero'][model] / 1e6:.2f}")
    # ranges used in the text: worst drop of the weight-preserving arms on defended certification
    keep = ["quant_2x_fp16", "quant_4x_int8", "quant_8x_int4", "prune_2x", "prune_4x", "prune_8x"]
    for s in (5, 8):
        diffs = [paired(values[f"cert{s} def"][m], values[f"cert{s} def"][BASE])["diff"] for m in keep]
        mac.put(f"keepworst{s}", f"{abs(min(diffs)) * 100:.1f}")
        mac.put(f"keepbest{s}", f"{max(diffs) * 100:.1f}")
    # LaVAN untargeted side 8 robust accuracy across all models (it breaks every model)
    l8 = [ms(values, "L8 robust", m)[0] for m in MODELS]
    mac.put("l8max", f1(max(l8)))
    mac.put("nseeds", str(len(SEEDS)))

    # C5: across the 13 models (seed means), what tracks defended certification? Pearson r; the models share
    # a baseline, so r is descriptive, not a test.
    def r(x, y):
        xs = [ms(values, x, m)[0] for m in MODELS]
        ys = [ms(values, y, m)[0] for m in MODELS]
        return float(np.corrcoef(xs, ys)[0, 1])
    corr = {"noise8:cert5def": r("Noise8 acc", "cert5 def"), "noise8:cert8def": r("Noise8 acc", "cert8 def"),
            "defclean:cert5def": r("def clean", "cert5 def"), "defclean:cert8def": r("def clean", "cert8 def"),
            "twomask5:cert5def": r("def 2mask5", "cert5 def"), "twomask8:cert8def": r("def 2mask8", "cert8 def"),
            "clean:u8acc": r("clean", "U8 acc"), "noise8:u8acc": r("Noise8 acc", "U8 acc")}
    for k, v in corr.items():
        mac.put(f"corr:{k}", f"{v:.2f}".replace("-", "$-$"))
    # amplification: drop in defended certification per pp of defended clean accuracy lost (dense-small, KD at 8x)
    for m in ["dense_small_4x", "dense_small_8x", "kd_4x", "kd_8x"]:
        dc = paired(values["def clean"][m], values["def clean"][BASE])["diff"]
        for s in (5, 8):
            dcert = paired(values[f"cert{s} def"][m], values[f"cert{s} def"][BASE])["diff"]
            mac.put(f"amp{s}:{m}", f"{dcert / dc:.1f}")

    # physical EOT ablation, seed 42 only
    phys = []
    for model in ["baseline_resnet18", "quant_4x_int8", "prune_4x", "dense_small_4x", "kd_4x"]:
        loc, ph = _load(f"universal_{model}"), _load(f"universal_physical_{model}")
        row = [loc["side_8"]["effective_patched_acc"]["mean"], loc["side_8"]["effective_target_success"]["mean"],
               ph["side_8"]["effective_patched_acc"]["mean"], ph["side_8"]["effective_target_success"]["mean"]]
        for k, v in zip(["locacc", "lochit", "physacc", "physhit"], row):
            mac.put(f"phys{k}:{model}", f1(v))
        phys.append([LABEL[model]] + [f1(v) for v in row])
    table(OUT / "tab_physical.tex", ["Model", "Loc.\\ acc", "Loc.\\ hit", "Phys.\\ acc", "Phys.\\ hit"], phys, "lrrrr")

    # ---- tables
    rows = []
    for model in MODELS:
        rows.append([LABEL[model], f"{extra['ratio'][model]:.2f}$\\times$", f"{extra['nonzero'][model] / 1e6:.2f}M",
                     cell(values, "clean", model), cell(values, "def clean", model)])
    table(OUT / "tab_models.tex", ["Model", "Storage", "Nonzero", "Clean (vanilla)", "Clean (defended)"], rows,
          "lrrrr", ROW_GROUPS)

    att = ["U5 acc", "U8 acc", "U8 hit", "Noise8 acc", "L5 robust", "L5 tgt hit", "L8 tgt hit"]
    rows = [[LABEL[m]] + [cell(values, k, m) for k in att] for m in MODELS]
    table(OUT / "tab_attacks.tex", ["Model", "U5 acc", "U8 acc", "U8 hit", "Noise8 acc", "L5 rob.", "L5 hit", "L8 hit"],
          rows, "l" + "r" * len(att), ROW_GROUPS)

    cert = ["cert5 vanilla", "cert8 vanilla", "def clean5 (PC)", "def 2mask5", "cert5 def", "def 2mask8", "cert8 def"]
    rows = [[LABEL[m]] + [cell(values, k, m) for k in cert] for m in MODELS]
    table(OUT / "tab_cert.tex", ["Model", "Cert-5", "Cert-8", "Clean (PC)", "2-mask-5", "Cert-5", "2-mask-8", "Cert-8"], rows,
          "l" + "r" * len(cert), ROW_GROUPS)

    trf = ["T U8 hit full->comp", "T U8 hit comp->full", "T L5 rate full->comp", "T L5 rate comp->full", "T L5 noise"]
    rows = [[LABEL[m]] + [cell(values, k, m) for k in trf] for m in MODELS[1:]]
    table(OUT / "tab_transfer.tex", ["Model", "U8 F$\\to$C", "U8 C$\\to$F", "L5 F$\\to$C", "L5 C$\\to$F", "L5 noise"],
          rows, "l" + "r" * len(trf), {2, 5, 8})

    # paired differences: vs baseline, and RQ4 (pruned / KD vs dense-small)
    dm = ["clean", "U8 acc", "L5 robust", "cert5 def", "cert8 def"]
    rows = []
    for label, a, b in comparisons():
        nice = f"{LABEL[a]} $-$ {LABEL[b]}"
        rows.append([nice] + [diff_cell(paired(values[k][a], values[k][b])) for k in dm])
    table(OUT / "tab_diffs.tex", ["Comparison", "Clean", "U8 acc", "L5 rob.", "Cert-5 (def)", "Cert-8 (def)"], rows,
          "lrrrrr", {2, 5, 8, 11, 14})

    mac.write(OUT / "macros.tex")

    # ---- figures
    plt.rcParams.update({"font.family": "serif", "font.serif": ["STIXGeneral", "DejaVu Serif"], "mathtext.fontset": "stix",
                         "font.size": 9, "axes.edgecolor": MUTED, "axes.labelcolor": INK, "xtick.color": MUTED,
                         "ytick.color": MUTED, "axes.spines.top": False, "axes.spines.right": False,
                         "axes.grid": True, "grid.color": "#e4e3df", "grid.linewidth": 0.6, "legend.frameon": False})

    def _legend(fig, ax):
        h, l = ax.get_legend_handles_labels()
        fig.legend(h, l, loc="outside lower center", ncols=4, fontsize=8)

    def ratio_panel(ax, metric, title, ylabel, label_last=True):
        b, bs = ms(values, metric, BASE)
        has_base = b is not None
        if has_base:
            ax.axhline(b * 100, color=MUTED, lw=1, ls=(0, (2, 2)), zorder=1)
        for fam, (models, col, mk, ls) in FAMILIES.items():
            ys = [ms(values, metric, m) for m in models]
            if any(y[0] is None for y in ys):
                continue
            xs = [1, 2, 4, 8] if has_base else [2, 4, 8]
            yv = ([b] if has_base else []) + [y[0] for y in ys]
            ye = ([bs] if has_base else []) + [y[1] for y in ys]
            ax.errorbar(xs, [v * 100 for v in yv], yerr=[e * 100 for e in ye], color=col, marker=mk, ls=ls, lw=2,
                        ms=6, capsize=2, elinewidth=1, mec="white", mew=0.8, label=fam, zorder=3)
            if label_last:
                ax.annotate(fam, (xs[-1], yv[-1] * 100), xytext=(6, 0), textcoords="offset points", va="center",
                            fontsize=7.5, color=INK)
        ax.set_xscale("log", base=2)
        ax.set_xticks([1, 2, 4, 8] if has_base else [2, 4, 8])
        ax.set_xticklabels([f"{x}$\\times$" for x in ax.get_xticks()])
        ax.set_xlim(0.85, 14)
        ax.set_title(title, fontsize=9, color=INK)
        ax.set_ylabel(ylabel)
        ax.set_xlabel("nominal compression")

    # Fig 1: defended certified accuracy (headline) + defended clean
    fig, axs = plt.subplots(1, 3, figsize=(6.75, 2.6), constrained_layout=True)
    ratio_panel(axs[0], "def clean", "Clean accuracy (defended)", "%", label_last=False)
    ratio_panel(axs[1], "cert5 def", "Certified, 5 px patch (2.4%)", "%", label_last=False)
    ratio_panel(axs[2], "cert8 def", "Certified, 8 px patch (6.25%)", "%", label_last=False)
    _legend(fig, axs[0])
    fig.savefig(FIG / "fig_cert.pdf")
    fig.savefig(FIG / "fig_cert.png", dpi=170)
    plt.close(fig)

    # Fig 2: empirical attacks
    fig, axs = plt.subplots(1, 3, figsize=(6.75, 2.6), constrained_layout=True)
    ratio_panel(axs[0], "U8 acc", "Universal 8 px: accuracy", "%", label_last=False)
    ratio_panel(axs[1], "L5 robust", "LaVAN 5 px: robust accuracy", "%", label_last=False)
    ratio_panel(axs[2], "Noise8 acc", "Noise 8 px (occlusion): accuracy", "%", label_last=False)
    _legend(fig, axs[0])
    fig.savefig(FIG / "fig_attacks.pdf")
    fig.savefig(FIG / "fig_attacks.png", dpi=170)
    plt.close(fig)

    # Fig 3: transfer, both directions, per family
    fig, axs = plt.subplots(1, 4, figsize=(6.75, 2.25), constrained_layout=True, sharey=True)
    for ax, (metric, title) in zip(axs, [("T U8 hit full->comp", "Universal 8 px\nfull $\\to$ compressed"),
                                         ("T U8 hit comp->full", "Universal 8 px\ncompressed $\\to$ full"),
                                         ("T L5 rate full->comp", "LaVAN 5 px\nfull $\\to$ compressed"),
                                         ("T L5 rate comp->full", "LaVAN 5 px\ncompressed $\\to$ full")]):
        ratio_panel(ax, metric, title, "transfer (%)" if ax in (axs[0], axs[2]) else "", label_last=False)
        ax.set_xlim(1.6, 10)
    nz = ms(values, "T L5 noise", "prune_4x")[0]
    for ax in axs[2:]:
        ax.axhline(nz * 100, color=MUTED, lw=0.8, ls=":", label="LaVAN noise control")
    for ax in axs:
        ax.set_ylim(bottom=0)
    h, l = axs[0].get_legend_handles_labels()
    h.append(matplotlib.lines.Line2D([], [], color=MUTED, lw=0.8, ls=":"))
    l.append("LaVAN noise control")
    fig.legend(h, l, loc="outside lower center", ncols=5, fontsize=8)
    fig.savefig(FIG / "fig_transfer.pdf")
    fig.savefig(FIG / "fig_transfer.png", dpi=170)
    plt.close(fig)

    # Fig 4: forest plot, paired differences (defended cert-5 and U8 acc) vs baseline and pruned vs dense-small
    comps = [c for c in comparisons() if c[2] == BASE] + [c for c in comparisons() if c[2] != BASE]
    fig, axs = plt.subplots(1, 3, figsize=(6.75, 4.2), constrained_layout=True, sharey=True)
    for ax, (metric, title) in zip(axs, [("cert5 def", "Certified 5 px (defended)"), ("cert8 def", "Certified 8 px (defended)"),
                                         ("U8 acc", "Universal 8 px accuracy")]):
        for i, (label, a, b) in enumerate(comps):
            p = paired(values[metric][a], values[metric][b])
            fam = next(f for f, v in FAMILIES.items() if a in v[0])
            col, mk = FAMILIES[fam][1], FAMILIES[fam][2]
            y = len(comps) - i
            sig = p["lo"] > 0 or p["hi"] < 0
            ax.plot([p["lo"] * 100, p["hi"] * 100], [y, y], color=col, lw=2, solid_capstyle="round")
            ax.plot(p["diff"] * 100, y, marker=mk, color=col if sig else "white", mec=col, mew=1.5, ms=6, ls="none")
        ax.axvline(0, color=MUTED, lw=1)
        ax.axhline(len(comps) - 11.5, color="#c9c8c3", lw=0.8)
        ax.set_title(title, fontsize=9, color=INK)
        ax.set_xlabel("paired difference (pp)")
        ax.grid(axis="y", visible=False)
    axs[0].set_yticks(range(len(comps), 0, -1))
    axs[0].set_yticklabels([f"{LABEL[a]} $-$ {'base' if b == BASE else LABEL[b]}" for _, a, b in comps], fontsize=7.5)
    fig.savefig(FIG / "fig_forest.pdf")
    fig.savefig(FIG / "fig_forest.png", dpi=170)
    plt.close(fig)

    # dump for the number check
    (OUT / "macros.json").write_text(json.dumps(mac.d, indent=1, sort_keys=True))
    print(f"{len(mac.d)} macros, tables and figures written")


if __name__ == "__main__":
    main()
